"""`turnin_probe` on a synthetic telemetry stream, at both sensor periods.

Two things are checked, and they are different things:

1. **The node's logic.**  It constructs against the real raceline, fires
   pulses only on the straights it selected, ramps the command and puts it
   back to zero, keeps the car near the line, and stops on the LiDAR guard.
2. **The instrument is calibrated.**  The stream is generated by a plant with
   a KNOWN pose-stamp-to-yaw-rate delay (transport + actuator dead time +
   yaw lag).  `tools/turnin_fit.py` must recover that number to within one
   sample at 0.058 s and at 0.104 s -- otherwise the probe cannot answer the
   0.03-0.055 s question it exists for.

The plant is deliberately continuous between ticks (sub-stepped at 2 ms),
because that is what makes the yaw onset sub-sample resolvable at all; the
actuator feedback is sampled at the ticks like the real one.
"""

