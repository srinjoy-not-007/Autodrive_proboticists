from pit_crew import vehicle                                   # noqa: E402
import turnin_fit                                              # noqa: E402

LINE = os.path.join(DATA, 'racelines', 'porto_mesh_safe.csv')

V = 2.5                 # m/s the synthetic car holds
SUB = 0.002             # s, plant integration step


# ------------------------------------------------------------------ plant

class Plant:
    """Bicycle car whose rack answers commands after a known dead time.

    ``transport`` is the age of a pose when its callback runs, ``dead`` the
    publish-to-rack delay and ``yaw_lag`` the rack-to-yaw-rate delay.  The
    total a correct fit must return is ``transport + dead + yaw_lag``.
    """

    def __init__(self, x, y, yaw, dead=0.100, yaw_lag=0.030, v=V,
                 slew=vehicle.STEER_RATE):
        self.t = 0.0
        self.x, self.y, self.yaw = x, y, yaw
        self.v = v
        self.rack = 0.0
        self.dead = float(dead)
        self.yaw_lag = float(yaw_lag)
        self.slew = float(slew)
        self.cmds = [(-1e9, 0.0)]      # (publish time, command)
        self.wz_hist = [(-1e9, 0.0)]   # yaw rate before the lag
        self.wheel = 0.0               # cumulative wheel angle, rad

    def publish(self, t, cmd):
        self.cmds.append((t, float(cmd)))

    def _cmd_at(self, t):
        c = 0.0
        for ct, cv in self.cmds:
            if ct <= t:
                c = cv
            else:
                break
        return c

    def _wz_at(self, t):
        w = 0.0
        for wt, wv in self.wz_hist:
            if wt <= t:
                w = wv
            else:
                break
        return w

    def advance_to(self, t_end):
        while self.t < t_end - 1e-12:
            h = min(SUB, t_end - self.t)
            target = self._cmd_at(self.t - self.dead)
            d = target - self.rack
            self.rack += max(-self.slew * h, min(self.slew * h, d))
            self.wz_hist.append(
                (self.t, self.v * math.tan(self.rack) / vehicle.WHEELBASE))
            wz = self._wz_at(self.t - self.yaw_lag)
            self.yaw += wz * h
            self.x += self.v * math.cos(self.yaw) * h
            self.y += self.v * math.sin(self.yaw) * h
            self.wheel += self.v / vehicle.WHEEL_RADIUS * h
            self.t += h
            if len(self.wz_hist) > 4000:
                del self.wz_hist[:2000]

    @property
    def wz(self):
        return self._wz_at(self.t - self.yaw_lag)


# ----------------------------------------------------------------- driving

def stamp_of(t):
    from sensor_msgs.msg import LaserScan
    s = LaserScan().header.stamp
    s.sec = int(t)
    s.nanosec = int(round((t - int(t)) * 1e9))
    return s


def make_node(tmp_path, dt, **over):
    from pit_crew import turnin_probe
    ov = dict(raceline_csv=LINE, map_prefix='', out_dir=str(tmp_path),
              warmup_s=1.0, v_probe=V, amp_rad=0.12, ramp_radps=0.25,
              pulse_s=0.70, recover_s=1.00, n_pulses=3, trigger_gap_m=4.0,
              cte_gate=0.25, v_gate=1.0, clear_min=0.60, kappa_max=0.15,
              max_run_s=120.0)
    ov.update(over)
    rclpy_stub.set_overrides(ov)
    try:
        return turnin_probe.TurnInProbe()
    finally:
        rclpy_stub.set_overrides({})


def run(node, dt, seconds, transport=0.020, dead=0.100, yaw_lag=0.030,
        lidar_min=0.9, lidar_after=None):
    """Feed the node one telemetry tick every `dt`, exactly as the sim does.

    Order inside a tick is the devkit's: sensors first, then the pose whose
    callback is where every command is published.
    """
    from geometry_msgs.msg import Point, PoseStamped
    from sensor_msgs.msg import Imu, JointState, LaserScan
    from std_msgs.msg import Float32

    j0 = node.path.nearest(*node.path.xy[0], None)
    x0, y0 = node.path.xy[j0]
    plant = Plant(float(x0), float(y0), float(node.path.yaw[j0]),
                  dead=dead, yaw_lag=yaw_lag)
    rclpy_stub.reset_clock()
    t0 = rclpy_stub.now_s()
    n = int(seconds / dt)
    for k in range(n):
        tick = k * dt                       # the stamp the telemetry carries
        recv = tick + transport             # when our callbacks run
        plant.advance_to(recv)
        rclpy_stub.advance(t0 + recv - rclpy_stub.now_s())

        lm = lidar_min if (lidar_after is None or tick < lidar_after) else 0.2
        scan = LaserScan()
        scan.header.stamp = stamp_of(t0 + tick)
        scan.ranges = [float(lm)] * 32
        node.stub_deliver('/lidar', scan)

        node.stub_deliver('/steering', Float32(data=float(plant.rack)))

        imu = Imu()
        imu.header.stamp = stamp_of(t0 + tick)
        imu.angular_velocity.z = float(plant.wz)
        node.stub_deliver('/imu', imu)

        for side in ('left_encoder', 'right_encoder'):
            js = JointState()
            js.header.stamp = stamp_of(t0 + tick)
            js.position = [float(plant.wheel)]
            node.stub_deliver('/' + side, js)

        node.stub_deliver('/ips', Point(x=float(plant.x), y=float(plant.y),
                                        z=0.0))

        ps = PoseStamped()
        ps.header.stamp = stamp_of(t0 + tick)
        ps.pose.position.x = float(plant.x)
        ps.pose.position.y = float(plant.y)
        ps.pose.orientation.z = math.sin(plant.yaw / 2.0)
        ps.pose.orientation.w = math.cos(plant.yaw / 2.0)
        node.stub_deliver('/pit_crew/pose', ps)

        cmd = node.stub_published('/steering_command')
        if cmd:
            plant.publish(rclpy_stub.now_s() - t0,
                          cmd[-1].data * vehicle.MAX_STEER)
        node.stub_fire_timers()
        if node.done:
            break
    node.finish()
    return plant


# ------------------------------------------------------------------- tests

@pytest.mark.parametrize('dt', [0.058, 0.104])
def test_probe_fires_ramps_and_reverts(tmp_path, dt):
    node = make_node(tmp_path, dt)
    assert node.triggers, 'no trigger point selected on the shipping line'
    assert not node.get_logger().errors()
    run(node, dt, 40.0)

    rows = turnin_fit.load(node.path_csv)
    assert rows
    pulse_rows = [r for r in rows
                  if r['src'] == 'pose' and r['phase'] == 'pulse']
    assert node.pulse_id >= 2, f'only {node.pulse_id} pulses in 40 s at {dt}'

    # every pulse ramps up and is put back to exactly zero afterwards
    for pid in sorted({int(r['pulse_id']) for r in pulse_rows}):
        p = [r for r in pulse_rows if int(r['pulse_id']) == pid]
        # the ramp starts from the tracking command it was added to
        assert abs(p[0]['cmd_steer']) < 0.08
        assert (max(abs(r['cmd_steer']) for r in p)
                - abs(p[0]['cmd_steer'])) > 0.05
        after = [r for r in rows
                 if r['src'] == 'pose' and int(r['pulse_id']) == pid
                 and r['phase'] == 'recover']
        assert after, 'no recovery phase logged'
    # and it fires on the straights it chose, never in a corner
    for r in pulse_rows:
        j = node.path.nearest(r['x'], r['y'], None, yaw=r['yaw'])
        assert abs(node.path.kappa[j]) <= 0.15 + 1e-9
    assert max(abs(r['cte']) for r in rows if r['src'] == 'pose') < 0.9
    assert not node.get_logger().errors()


def test_lidar_guard_stops_the_run(tmp_path):
    node = make_node(tmp_path, 0.104)
    run(node, 0.104, 30.0, lidar_after=8.0)
    assert node.done and node.abort and 'obstacle' in node.abort
    zeros = node.stub_published('/steering_command')[-3:]
    assert all(abs(m.data) < 1e-12 for m in zeros)
    assert all(abs(m.data) < 1e-12
               for m in node.stub_published('/throttle_command')[-3:])


@pytest.mark.parametrize('dt,dead,yaw_lag', [(0.058, 0.100, 0.030),
                                             (0.104, 0.150, 0.030),
                                             (0.058, 0.060, 0.055)])
def test_fitted_delay_equals_the_injected_one(tmp_path, dt, dead, yaw_lag):
    """The calibration: fit(total) == transport + dead + yaw_lag, +-one sample."""
    transport = 0.020
    node = make_node(tmp_path, dt)
    run(node, dt, 95.0, transport=transport, dead=dead, yaw_lag=yaw_lag)

    rows = turnin_fit.load(node.path_csv)
    recs = turnin_fit.pulses(rows)
    assert len(recs) >= 2, f'{len(recs)} pulses fitted at dt {dt}'

    period = turnin_fit.period_of(rows)
    assert abs(period - dt) < 0.2 * dt

    injected = transport + dead + yaw_lag
    got = float(np.nanmedian([r['total'] for r in recs if r['quiet']]))
    assert abs(got - injected) <= dt, (
        f'dt {dt}: fitted total {got:.4f} s against injected '
        f'{injected:.4f} s (one sample is {dt:.4f} s)')

    # `dead_cmd_fb` is the tick-quantised one: the rack finishes each held
    # increment between ticks, so the feedback can only ever date the command
    # to a whole period, and the zero-order-hold convention `pulses()` uses
    # shifts it by up to another one.  Hence 1.5 samples here, against one for
    # `total` -- and it is `total` that the phase-shift question is about.
    quiet = [r for r in recs if r['quiet']]
    d_fb = float(np.nanmedian([r['dead_cmd_fb'] for r in quiet]))
    assert abs(d_fb - dead) <= 1.5 * dt, f'dead_cmd_fb {d_fb:.4f} vs {dead}'
    slew = float(np.nanmedian([r['slew'] for r in quiet]))
    assert 0.18 < slew < 0.35, f'rack ramp {slew:.3f} rad/s, asked 0.25'


def test_two_rates_report_the_same_delay(tmp_path):
    """Same plant, two periods: the fit must not invent a rate dependence.

    This is the null the live experiment is measured against.  If the probe
    itself reported different delays at 0.058 and 0.104 for an identical
    plant, a live difference would mean nothing.
    """
    out = {}
    for dt in (0.058, 0.104):
        node = make_node(tmp_path / f'r{int(dt * 1000)}', dt)
        run(node, dt, 95.0, dead=0.100, yaw_lag=0.030)
        recs = turnin_fit.pulses(turnin_fit.load(node.path_csv))
        assert len(recs) >= 2
        out[dt] = float(np.nanmedian([r['total'] for r in recs if r['quiet']]))
    assert abs(out[0.058] - out[0.104]) <= 0.104, (
        f'probe invents a rate dependence: {out}')
